"""Write src/ops_app/static/land.js, the operations map's land outline (operations map spec §4.4),
from Natural Earth's 1:110m land GeoJSON.

Usage: python tools/ops_app/make_land.py <ne_110m_land.geojson>
Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

LON = (-130.0, 60.0)
LAT = (-50.0, 75.0)
TARGET = Path(__file__).resolve().parents[2] / "src" / "ops_app" / "static" / "land.js"
HEADER = """// Land outline for the operations map (spec 2026-11-11 operations map §4.4).
// Generated by tools/ops_app/make_land.py from Natural Earth 1:110m land, release v5.1.2
// (nvkelso/natural-earth-vector, geojson/ne_110m_land.geojson), public domain. Rings with a
// point inside longitude -130..60 and latitude -50..75, rounded to 0.1 degree; [[lon, lat], ...].
"""


def rings(geojson: dict[str, object]) -> list[list[list[float]]]:
    kept = []
    for feature in geojson["features"]:  # type: ignore[union-attr]
        geometry = feature["geometry"]
        polygons = (
            [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        )
        for polygon in polygons:
            ring = polygon[0]
            if not any(LON[0] <= x <= LON[1] and LAT[0] <= y <= LAT[1] for x, y in ring):
                continue
            points: list[list[float]] = []
            for x, y in ring:
                point = [round(x, 1), round(y, 1)]
                if not points or points[-1] != point:
                    points.append(point)
            if len(points) > 3:
                kept.append(points)
    return kept


def main(source: str) -> None:
    outline = rings(json.loads(Path(source).read_text(encoding="utf-8")))
    body = json.dumps(outline, separators=(",", ":"))
    TARGET.write_text(f'{HEADER}"use strict";\nconst LAND = {body};\n', encoding="utf-8")
    points = sum(len(ring) for ring in outline)
    print(f"{TARGET.name}: {len(outline)} rings, {points} points, {TARGET.stat().st_size} bytes")


if __name__ == "__main__":
    main(sys.argv[1])
